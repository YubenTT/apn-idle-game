import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import {
  readJson,
  stableJson,
  validateCatalogPolicy,
  validatePackManifest,
  validateRightsDocument,
} from './lib.mjs';

const defaultRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

const fail = (label, message) => {
  throw new Error(`${label}: ${message}`);
};

const inside = (parent, child) => {
  const relative = path.relative(parent, child);
  return relative === '' || (!relative.startsWith('..') && !path.isAbsolute(relative));
};

const authorityFile = (rootDir, packDirectory, relativePath, label) => {
  if (typeof relativePath !== 'string') fail(label, 'portable path is required');
  const absolute = path.resolve(rootDir, relativePath);
  if (!inside(rootDir, absolute) || !inside(packDirectory, absolute)) {
    fail(label, 'authority path escapes its Pack directory');
  }
  if (!fs.existsSync(absolute)) fail(label, `missing authority file ${relativePath}`);
  if (fs.lstatSync(absolute).isSymbolicLink()) {
    fail(label, 'authority file must not be a symbolic link');
  }
  const realPackDirectory = fs.realpathSync(packDirectory);
  const realAbsolute = fs.realpathSync(absolute);
  if (!inside(realPackDirectory, realAbsolute)) {
    fail(label, 'authority file resolves outside its Pack directory');
  }
  return absolute;
};

const normalizedMark = (value) =>
  String(value || '')
    .normalize('NFKC')
    .toLocaleLowerCase('en-US')
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim();

const titleUsesMark = (title, mark) => {
  const normalizedTitle = ` ${normalizedMark(title)} `;
  const normalizedDenied = normalizedMark(mark);
  return normalizedDenied.length > 0 && normalizedTitle.includes(` ${normalizedDenied} `);
};

export const catalogModuleSource = (packs, policy) =>
  `// Generated by scripts/assets/generate-catalog.mjs. Do not edit.\n` +
  `const deepFreeze = (value) => {\n` +
  `  if (value && typeof value === 'object' && !Object.isFrozen(value)) {\n` +
  `    Object.freeze(value);\n` +
  `    for (const child of Object.values(value)) deepFreeze(child);\n` +
  `  }\n` +
  `  return value;\n` +
  `};\n\n` +
  `export const CATALOG_NOTICE = ${JSON.stringify(policy.nonAffiliationNotice)};\n\n` +
  `export const GAME_PACKS = deepFreeze(${JSON.stringify(packs, null, 2)});\n\n` +
  `export const PACK_BY_ID = deepFreeze(Object.fromEntries(GAME_PACKS.map((pack) => [pack.id, pack])));\n`;

export function buildCatalog(options = {}) {
  const rootDir = path.resolve(options.rootDir || defaultRoot);
  const packsRoot = path.join(rootDir, 'assets/game-packs');
  const catalogPath = path.join(packsRoot, 'catalog.json');
  const modulePath = path.join(rootDir, 'js/generated/game-packs.js');
  const policyPath = path.join(packsRoot, 'catalog-policy.json');
  const write = options.write !== false;
  const warn = typeof options.warn === 'function' ? options.warn : console.warn;

  if (!fs.existsSync(policyPath)) fail('catalog-policy', 'missing catalog-policy.json');
  const policy = readJson(policyPath);
  const policyErrors = validateCatalogPolicy(policy);
  if (policyErrors.length) throw new Error(policyErrors.join('\n'));

  const manifestPaths = fs
    .readdirSync(packsRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => path.join(packsRoot, entry.name, 'pack.json'))
    .filter((file) => fs.existsSync(file))
    .sort();
  const sourcePacks = manifestPaths.map((file) => readJson(file));
  const sourceErrors = sourcePacks.flatMap((pack) =>
    validatePackManifest(pack, pack?.id || 'pack'),
  );
  if (new Set(sourcePacks.map((pack) => pack.id)).size !== sourcePacks.length) {
    sourceErrors.push('catalog: duplicate id');
  }
  if (new Set(sourcePacks.map((pack) => pack.order)).size !== sourcePacks.length) {
    sourceErrors.push('catalog: duplicate order');
  }
  if (sourceErrors.length) throw new Error(sourceErrors.join('\n'));
  const sourceIds = new Set(sourcePacks.map((pack) => pack.id));
  const unknownPendingWarnId = policy.pendingReviewWarnIds.find(
    (id) => !sourceIds.has(id),
  );
  if (unknownPendingWarnId) {
    fail('catalog-policy', `pendingReviewWarnIds contains unknown Pack ${unknownPendingWarnId}`);
  }

  const resolved = sourcePacks.map((pack) => {
    const packDirectory = path.join(packsRoot, pack.id);
    authorityFile(rootDir, packDirectory, pack.sourceBoard, `${pack.id}/sourceBoard`);
    const rightsPath = authorityFile(
      rootDir,
      packDirectory,
      pack.rights,
      `${pack.id}/rights`,
    );
    const rights = readJson(rightsPath);
    const rightsErrors = validateRightsDocument(rights, `${pack.id}/rights`);
    if (rightsErrors.length) throw new Error(rightsErrors.join('\n'));
    if (rights.editorialReference !== pack.editorialReference) {
      fail(pack.id, 'editorialReference does not match rights authority');
    }
    if (rights.provenance.sourceBoard !== pack.sourceBoard) {
      fail(pack.id, 'rights provenance does not bind the Pack source board');
    }
    if (rights.killSwitch !== `disable-${pack.id}`) {
      fail(pack.id, `killSwitch must equal disable-${pack.id}`);
    }
    return { ...pack, rights };
  });

  const deniedMarks = new Set(policy.deniedRuntimeMarks.map(normalizedMark));
  for (const pack of resolved) {
    const editorialMark = normalizedMark(pack.editorialReference);
    if (editorialMark && !deniedMarks.has(editorialMark)) {
      fail(pack.id, 'editorialReference is missing from deniedRuntimeMarks');
    }
    const runtimeIdentities = [
      pack.title,
      ...pack.targets.map((target) => target.label),
      pack.boss.label,
    ];
    const matchedMark = policy.deniedRuntimeMarks.find((mark) =>
      runtimeIdentities.some((identity) => titleUsesMark(identity, mark)),
    );
    if (matchedMark) {
      fail(pack.id, `runtime identity uses denied editorial mark "${matchedMark}"`);
    }
    const matchedTerm = policy.deniedRuntimeTerms.find((term) =>
      runtimeIdentities.some((identity) => titleUsesMark(identity, term)),
    );
    if (matchedTerm) {
      fail(pack.id, `runtime identity uses denied third-party term "${matchedTerm}"`);
    }
  }

  const warnings = [];
  const emitWarning = (message) => {
    warnings.push(message);
    warn(message);
  };
  const disabled = new Set(policy.disabledKillSwitches);
  const pendingWarnIds = new Set(policy.pendingReviewWarnIds);
  const stalePendingWarnId = resolved.find(
    (pack) =>
      pendingWarnIds.has(pack.id) &&
      !['pending-review', 'blocked'].includes(pack.rights.mode),
  )?.id;
  if (stalePendingWarnId) {
    fail(
      'catalog-policy',
      `pendingReviewWarnIds contains resolved Pack ${stalePendingWarnId}; remove the transitional exception`,
    );
  }
  const packs = resolved
    .sort((left, right) => left.order - right.order || left.id.localeCompare(right.id))
    .filter((pack) => {
      if (pack.rights.mode === 'blocked') {
        emitWarning(`CATALOG EXCLUDE ${pack.id}: rights mode blocked`);
        return false;
      }
      if (disabled.has(pack.rights.killSwitch)) {
        emitWarning(`CATALOG EXCLUDE ${pack.id}: kill switch ${pack.rights.killSwitch}`);
        return false;
      }
      if (pack.rights.mode === 'pending-review') {
        if (!pendingWarnIds.has(pack.id) && policy.pendingReview === 'block') {
          emitWarning(`CATALOG EXCLUDE ${pack.id}: pending-review blocked by policy`);
          return false;
        }
        emitWarning(
          `RIGHTS WARN ${pack.id}: pending-review (needs-legal-review; no approval claimed)`,
        );
      }
      return true;
    });

  if (write) {
    fs.mkdirSync(path.dirname(modulePath), { recursive: true });
    fs.writeFileSync(catalogPath, stableJson(packs));
    fs.writeFileSync(modulePath, catalogModuleSource(packs, policy));
  }
  return {
    packs,
    policy,
    warnings,
    sourceCount: sourcePacks.length,
    activeCount: packs.length,
    manifestPaths,
  };
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  const result = buildCatalog();
  console.log(`CATALOG ${result.activeCount}/${result.sourceCount} active packs`);
}
